logger = logging.getLogger(__name__)


class LLMTestFramework(StrEnum):
    """Test frameworks supported by LLM generator."""

    PYTEST = "pytest"  # Python
    JUNIT = "junit"  # Java
    NUNIT = "nunit"  # C#
    MOCHA = "mocha"  # JavaScript/TypeScript
    JEST = "jest"  # TypeScript
    PHPUNIT = "phpunit"  # PHP — Story 1.55 (FR24/FR12)
    PEST = "pest"  # PHP (DSL nad PHPUnit) — Story 1.55 (FR24/FR12)
    SELENIUM = "selenium"  # E2E — Story 1.56 (AC3)
    PLAYWRIGHT = "playwright"  # E2E — Story 1.56 (AC3)
    APPIUM = "appium"  # E2E mobilne — Story 1.56 (AC3)
    UNITTEST = "unittest"  # Python (natywny) — Story 1.57
    TESTNG = "testng"  # Java — Story 1.57
    MSTEST = "mstest"  # C# — Story 1.57


class LLMTestType(StrEnum):
    """Types of AI-generated tests."""

    INTELLIGENT = "intelligent"  # AI-revealed scenarios
    EDGE_CASE = "edge_case"  # Boundary conditions
    SECURITY = "security"  # Security-focused tests
    PERFORMANCE = "performance"  # Performance tests
    ACCESSIBILITY = "accessibility"  # A11y tests
    SEMANTIC = "semantic"  # Behavior-based tests


@dataclass
class LLMTestScenario:
    """A test scenario identified by AI."""

    name: str
    description: str
    test_type: LLMTestType
    rationale: str  # Why this test is important
    preconditions: list[str] = field(default_factory=list)
    test_data: dict[str, Any] | None = None
    expected_behavior: str | None = None
    edge_case_description: str | None = None


@dataclass
class LLMGeneratedTest:
    """A test case generated by LLM."""

    name: str
    description: str
    test_type: LLMTestType
    framework: LLMTestFramework
    language: str
    code: str  # Generated test code
    source_file: str
    source_function: str | None = None
    scenario: LLMTestScenario | None = None
    confidence: float = 0.0  # 0.0 to 1.0
    tokens_used: int = 0


@dataclass
class LLMTestSuite:
    """A collection of LLM-generated test cases."""

    name: str
    framework: LLMTestFramework
    language: str
    source_files: list[str] = field(default_factory=list)
    scenarios: list[LLMTestScenario] = field(default_factory=list)
    test_cases: list[LLMGeneratedTest] = field(default_factory=list)
    generated_at: datetime = field(default_factory=datetime.utcnow)
    total_tokens_used: int = 0
    generation_metadata: dict[str, Any] = field(default_factory=dict)

    def get_statistics(self) -> dict[str, Any]:
        """Get test suite statistics."""
        test_types = {}
        for tc in self.test_cases:
            test_types[tc.test_type] = test_types.get(tc.test_type, 0) + 1

        avg_confidence = sum(tc.confidence for tc in self.test_cases) / len(self.test_cases) if self.test_cases else 0.0

        return {
            "total_tests": len(self.test_cases),
            "total_scenarios": len(self.scenarios),
            "test_types": test_types,
            "source_files_count": len(self.source_files),
            "total_tokens_used": self.total_tokens_used,
            "average_confidence": avg_confidence,
        }

    def to_dict(self) -> dict:
        """Convert test suite to dictionary."""
        return {
            "name": self.name,
            "framework": self.framework,
            "language": self.language,
            "source_files": self.source_files,
            "scenarios": [
                {
                    "name": s.name,
                    "description": s.description,
                    "test_type": s.test_type,
                    "rationale": s.rationale,
                    "preconditions": s.preconditions,
                    "test_data": s.test_data,
                    "expected_behavior": s.expected_behavior,
                }
                for s in self.scenarios
            ],
            "test_cases": [
                {
                    "name": tc.name,
                    "description": tc.description,
                    "test_type": tc.test_type,
                    "code": tc.code,
                    "source_file": tc.source_file,
                    "source_function": tc.source_function,
                    "confidence": tc.confidence,
                    "tokens_used": tc.tokens_used,
                }
                for tc in self.test_cases
            ],
            "generated_at": self.generated_at.isoformat(),
            "total_tokens_used": self.total_tokens_used,
            "statistics": self.get_statistics(),
            "generation_metadata": self.generation_metadata,
        }


class LLMTestGenerator:
    """Generates test cases using LLM for sophisticated scenarios."""

    def __init__(
        self,
        llm_gateway: LLMGateway | None = None,
        prompt_manager: PromptManager | None = None,
    ):
        self.llm_gateway = llm_gateway or get_llm_gateway()
        self.prompt_manager = prompt_manager or get_prompt_manager()

    async def generate_test_scenarios(
        self,
        source_code: str,
        file_path: str,
        language: str,
        analysis_result: dict[str, Any] | None = None,
        provider: LLMProvider = LLMProvider.OPENAI,
        model: str | None = None,
    ) -> list[LLMTestScenario]:
        """
        Generate test scenarios using AI analysis.

        Args:
            source_code: Source code to analyze
            file_path: File path for context
            language: Programming language
            analysis_result: Previous analysis result for context
            provider: LLM provider to use
            model: Model override (optional)

        Returns:
            List of test scenarios
        """
        try:
            # Build prompt
            prompt = self._build_scenario_prompt(source_code, file_path, language, analysis_result)

            # Get LLM response
            response = await self.llm_gateway.complete(
                provider=provider,
                messages=[{"role": "user", "content": prompt}],
                model=model,
                module="test_generation",
                task_type="generate_scenarios",
            )

            # Parse scenarios
            scenarios = self._parse_scenarios(response.content, file_path)

            logger.info(f"Generated {len(scenarios)} test scenarios for {file_path}")
            return scenarios

        except Exception as e:
            logger.error(f"Failed to generate test scenarios: {e}")
            return []

    async def generate_test_code(
        self,
        scenario: LLMTestScenario,
        source_code: str,
        file_path: str,
        language: str,
        framework: LLMTestFramework = LLMTestFramework.PYTEST,
        provider: LLMProvider = LLMProvider.OPENAI,
        model: str | None = None,
    ) -> LLMGeneratedTest | None:
        """
        Generate test code for a scenario.

        Args:
            scenario: Test scenario to generate code for
            source_code: Source code being tested
            file_path: File path for context
            language: Programming language
            framework: Test framework
            provider: LLM provider to use
            model: Model override (optional)

        Returns:
            Generated test or None if failed
        """
        try:
            # Build prompt
            prompt = self._build_test_code_prompt(scenario, source_code, file_path, language, framework)

            # Get LLM response
            response = await self.llm_gateway.complete(
                provider=provider,
                messages=[{"role": "user", "content": prompt}],
                model=model,
                module="test_generation",
                task_type="generate_test_code",
            )

            # Create generated test
            test = LLMGeneratedTest(
                name=scenario.name,
                description=scenario.description,
                test_type=scenario.test_type,
                framework=framework,
                language=language,
                code=response.content,
                source_file=file_path,
                source_function=self._extract_function_name(scenario, file_path),
                scenario=scenario,
                confidence=0.8,
                tokens_used=response.total_tokens,
            )

            logger.info(f"Generated test code: {scenario.name}")
            return test

        except Exception as e:
            logger.error(f"Failed to generate test code: {e}")
            return None

    async def generate_test_suite(
        self,
        source_files: list[tuple[str, str]],  # (file_path, source_code)
        language: str,
        framework: LLMTestFramework = LLMTestFramework.PYTEST,
        analysis_results: dict[str, Any] | None = None,
        provider: LLMProvider = LLMProvider.OPENAI,
        model: str | None = None,
    ) -> LLMTestSuite:
        """
        Generate a complete test suite for multiple files.

        Args:
            source_files: List of (file_path, source_code) tuples
            language: Programming language
            framework: Test framework
            analysis_results: Previous analysis results for context
            provider: LLM provider to use
            model: Model override (optional)

        Returns:
            Generated test suite
        """
        suite = LLMTestSuite(
            name=f"{language}_llm_tests",
            framework=framework,
            language=language,
            source_files=[fp for fp, _ in source_files],
        )

        for file_path, source_code in source_files:
            file_analysis = analysis_results.get(file_path, {}) if analysis_results else {}

            # Generate scenarios
            scenarios = await self.generate_test_scenarios(
                source_code=source_code,
                file_path=file_path,
                language=language,
                analysis_result=file_analysis,
                provider=provider,
                model=model,
            )

            suite.scenarios.extend(scenarios)

            # Generate tests for each scenario
            for scenario in scenarios[:5]:  # Limit to prevent excessive generation
                test = await self.generate_test_code(
                    scenario=scenario,
                    source_code=source_code,
                    file_path=file_path,
                    language=language,
                    framework=framework,
                    provider=provider,
                    model=model,
                )

                if test:
                    suite.test_cases.append(test)
                    suite.total_tokens_used += test.tokens_used

        suite.generation_metadata = {
            "provider": provider,
            "model": model,
            "files_processed": len(source_files),
        }

        logger.info(f"Generated test suite: {len(suite.test_cases)} tests, {suite.total_tokens_used} tokens")

        return suite

    def _build_scenario_prompt(
        self,
        source_code: str,
        file_path: str,
        language: str,
        analysis_result: dict[str, Any] | None = None,
    ) -> str:
        """Build prompt for scenario generation."""
        prompt = f"""Analyze the following {language} code and identify important test scenarios.

File: {file_path}

```{language}
{source_code}
```
"""

        if analysis_result:
            prompt += f"\nAdditional analysis context:\n{analysis_result}\n"

        prompt += """
Generate a JSON array of test scenarios. Each scenario should include:
- name: Short descriptive test name
- description: What this test validates
- test_type: One of: intelligent, edge_case, security, performance, accessibility, semantic
- rationale: Why this test is important
- preconditions: Array of setup conditions (if any)
- test_data: Example test data (if applicable)
- expected_behavior: What should happen
- edge_case_description: What edge case this covers (if applicable)

Focus on:
1. Edge cases and boundary conditions
2. Error handling and validation
3. Security considerations
4. Unusual input combinations
5. State-dependent behaviors

Return only valid JSON array.
"""
        return prompt

    def _build_test_code_prompt(
        self,
        scenario: LLMTestScenario,
        source_code: str,
        file_path: str,
        language: str,
        framework: LLMTestFramework,
    ) -> str:
        """Build prompt for test code generation."""
        prompt = f"""Generate test code for the following scenario.

Test Framework: {framework}
Language: {language}

Test Scenario:
- Name: {scenario.name}
- Description: {scenario.description}
- Type: {scenario.test_type}
- Rationale: {scenario.rationale}
"""

        if scenario.preconditions:
            prompt += f"- Preconditions: {', '.join(scenario.preconditions)}\n"

        if scenario.test_data:
            prompt += f"- Test Data: {scenario.test_data}\n"

        if scenario.expected_behavior:
            prompt += f"- Expected Behavior: {scenario.expected_behavior}\n"

        if scenario.edge_case_description:
            prompt += f"- Edge Case: {scenario.edge_case_description}\n"

        prompt += f"""
Source Code:
```{language}
{source_code}
```

Generate complete, executable test code. Include:
- Proper imports and setup
- Test implementation following the scenario
- Assertions validating expected behavior
- Comments explaining the test

Return only the test code.
"""
        return prompt

    def _parse_scenarios(self, response_content: str, file_path: str) -> list[LLMTestScenario]:
        """Parse scenarios from LLM response."""
        import json

        scenarios = []

        try:
            data = json.loads(response_content)

            for item in data if isinstance(data, list) else [data]:
                try:
                    scenario = LLMTestScenario(
                        name=item.get("name", "test_scenario"),
                        description=item.get("description", ""),
                        test_type=LLMTestType(item.get("test_type", "intelligent")),
                        rationale=item.get("rationale", ""),
                        preconditions=item.get("preconditions", []),
                        test_data=item.get("test_data"),
                        expected_behavior=item.get("expected_behavior"),
                        edge_case_description=item.get("edge_case_description"),
                    )
                    scenarios.append(scenario)
                except (ValueError, KeyError) as e:
                    logger.warning(f"Failed to parse scenario: {e}")
                    continue

        except json.JSONDecodeError as e:
            logger.error(f"Failed to parse scenarios JSON: {e}")

        return scenarios

    def _extract_function_name(self, scenario: LLMTestScenario, file_path: str) -> str | None:
        """Extract source function name from scenario or file path."""
        # Try to get function name from scenario name (e.g. "test_add_success" → "add")
        name = scenario.name
        if name.startswith("test_"):
            name = name[5:]
        # Remove common suffixes
        for suffix in ("_success", "_failure", "_error", "_edge_case", "_boundary"):
            if name.endswith(suffix):
                name = name[: -len(suffix)]
                break
        return name or None


def get_llm_test_generator() -> LLMTestGenerator:
    """Get or create LLM test generator instance."""
    return LLMTestGenerator()
